"""Validate data/controls.json against NIST's official CSF 2.0 informative references
and generate docs/framework-mapping.md and docs/csf2-reference.md."""
import json, sys
olir = json.load(open('data/csf2-olir.json'))
csf = {s['id']: s for s in olir['subcategories']}
ctl = json.load(open('data/controls.json'))['controls']
ig1 = json.load(open('data/cis-ig1.json'))['ig1']
errors, warn = [], []
key = lambda x: [int(p) for p in x.replace('Cl.', '').split('.')]

def fmt(refs, official, ig=None):
    out = []
    for r in refs:
        s = r + ('' if r in official else '\\*')
        if ig is not None and r not in ig: warn.append(f'CIS {r} is not IG1')
        out.append(s)
    return ', '.join(out) or '–'

rows, stats = [], {'iso': [0, 0], 'cis': [0, 0]}
for c in ctl:
    for s in c['csf']:
        if s not in csf: errors.append(f"{c['id']}: unknown CSF subcategory {s}")
    off_iso = {r for s in c['csf'] if s in csf for r in csf[s]['iso']}
    off_cis = {r for s in c['csf'] if s in csf for r in csf[s]['cis']}
    for r in c['iso']: stats['iso'][r in off_iso] += 1
    for r in c['cis']: stats['cis'][r in off_cis] += 1
    rows.append((c, fmt(c['iso'], off_iso), fmt(c['cis'], off_cis, ig1)))
if errors: sys.exit('\n'.join(errors))
covered = {r for c in ctl for r in c['cis']}
missing = [s for s in ig1 if s not in covered]
used_csf = {s for c in ctl for s in c['csf']}

L = ['# Framework mapping', '',
     '> Generated by `tools/build_mapping.py` from `data/controls.json`. Do not edit by hand.', '',
     'The toolkit\'s **32 controls** are written for a small business, in our own words. Each one is tagged with:', '',
     '- **CSF 2.0:** the NIST Cybersecurity Framework 2.0 subcategories it achieves (the backbone, [ADR 0001](adr/0001-nist-csf-backbone.md)).',
     '- **ISO 27001:** ISO/IEC 27001:2022 Annex A control numbers (`Cl.` = a mandatory clause). Numbers only; the standard\'s text is not reproduced.',
     '- **CIS IG1:** CIS Controls v8.1 Implementation Group 1 safeguard numbers.',
     '- **PDPA:** the Malaysian PDPA duty it supports (see [pdpa-summary.md](pdpa-summary.md)).', '',
     '**How references are checked.** NIST publishes official mappings from CSF 2.0 to ISO/IEC 27001:2022 and to CIS Controls v8.1 (its CSF 2.0 informative references, extracted to `data/csf2-olir.json`). '
     'A reference with no mark appears in NIST\'s mapping for at least one of the control\'s CSF subcategories. '
     'A reference marked **\\*** is our own mapping: it is not in NIST\'s file for those subcategories. '
     'NIST\'s CIS v8.1 references cover only 48 of 106 subcategories, so many CIS links are necessarily our own. '
     'Note: NIST\'s file lists clause "6.13" for ID.RA-06, which looks like a typo for 6.1.3. It is shown as given in the reference table.', '',
     f"**Check results:** ISO references {stats['iso'][1]} confirmed / {stats['iso'][0]} own mapping; "
     f"CIS references {stats['cis'][1]} confirmed / {stats['cis'][0]} own mapping. "
     f"CIS IG1 coverage: **{56-len(missing)} of 56** safeguards" + (f" (missing: {', '.join(missing)})" if missing else ' (all covered)') + '. '
     f"CSF 2.0 subcategories used: {len(used_csf)} of {len(csf)}.", '']
for fn in ['Govern', 'Identify', 'Protect', 'Detect', 'Respond', 'Recover']:
    L += [f'## {fn}', '', '| ID | Control | What it means | CSF 2.0 | ISO 27001 | CIS IG1 | PDPA |', '|---|---|---|---|---|---|---|']
    for c, iso, cis in rows:
        if c['fn'] == fn:
            L.append(f"| {c['id']} | **{c['title']}** | {c['what']} | {', '.join(c['csf'])} | {iso} | {cis} | {c['pdpa'] or '–'} |")
    L.append('')
L += ['## Sources', '- NIST, *CSF 2.0 Informative References* (bulk export, downloaded 11 Nov 2026), including *ISO/IEC 27001:2022 to CSF 2.0* (OLIR, final, posted 30 May 2025) and *CIS Controls v8.1 to CSF 2.0*. https://www.nist.gov/cyberframework/csf-20-informative-references',
      '- CIS, *CIS Critical Security Controls v8.1* (IG1 safeguard numbers). https://www.cisecurity.org/controls',
      '- The full CSF 2.0 to ISO/CIS reference table is in [csf2-reference.md](csf2-reference.md).', '']
open('docs/framework-mapping.md', 'w').write('\n'.join(L))

R = ['# CSF 2.0 reference table', '', '> Generated by `tools/build_mapping.py` from NIST\'s CSF 2.0 informative references. CSF text is from NIST (a U.S. government work). ISO and CIS appear as numbers only.', '',
     '| CSF 2.0 | Outcome (NIST wording) | ISO/IEC 27001:2022 | CIS v8.1 | Toolkit controls |', '|---|---|---|---|---|']
by = {}
for c in ctl:
    for s in c['csf']: by.setdefault(s, []).append(c['id'])
for s in olir['subcategories']:
    R.append(f"| {s['id']} | {s['text']} | {', '.join(sorted(s['iso'], key=key)) or '–'} | {', '.join(sorted(s['cis'], key=key)) or '–'} | {', '.join(by.get(s['id'], [])) or '–'} |")
open('docs/csf2-reference.md', 'w').write('\n'.join(R) + '\n')
print('ISO confirmed/own', stats['iso'][1], stats['iso'][0], '| CIS confirmed/own', stats['cis'][1], stats['cis'][0], '| IG1 missing', missing, '| CSF used', len(used_csf))
for w in sorted(set(warn)): print('WARN', w)
